def dms(deg: float) -> str:
    d = int(deg)
    mf = (deg - d) * 60
    m = int(mf)
    s = round((mf - m) * 60)

    if s == 60:
        s, m = 0, m + 1
    if m == 60:
        m, d = 0, d + 1

    return f'{d:02d}° {m:02d}\' {s:02d}"'


